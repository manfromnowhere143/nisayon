def scenario(name: str) -> Scenario:
    for item in SCENARIOS:
        if item.name == name:
            return item
    raise KeyError(name)


def write_scenario(item: Scenario, root: Path) -> Path:
    path = write_bundle(item.build(), Path(root) / item.name)
    if item.after_write is not None:
        item.after_write(path)
    return path


def synthetic_trace_digests() -> frozenset[str]:
    """Digests of every fixture trace as written, so relabelled fixtures can be recognized."""
    digests = set()
    for item in SCENARIOS:
        for trace in item.build().traces.values():
            digests.add(sha256_bytes(trace_bytes(trace)))
    return frozenset(digests)
