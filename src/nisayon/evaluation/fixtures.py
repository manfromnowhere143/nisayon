def make_run(
    run_id: str,
    revision_role: str,
    condition: str,
    started: datetime,
    *,
    candidate: dict | None = None,
    plan: dict | None = None,
    process: str = "completed",
    claimed_outcome: str | None = None,
    claimed_validity: str | None = None,
    identity: dict | None = None,
) -> dict:
    cond_index = COND_INDEX[condition]
    run = {
        "schema": "nisayon.run.v1",
        "id": run_id,
        "case_id": CASE_ID,
        "evidence_origin": ORIGIN,
        "started_at": wall(started),
        "revision": {
            "role": revision_role,
            "id": WORKING if revision_role == "working" else CHANGED,
        },
        "task": {"policy": dict(POLICY), "backend": dict(BACKEND)},
        "condition_id": condition,
        "candidate": candidate,
        "plan": plan or {"continuation": "full_rerun", "intervention": None},
        "process": {"status": process, "returncode": 0 if process == "completed" else None},
        "reset": {
            "procedure_id": "fixture-reset-v1",
            "initial_condition_id": condition,
            "evidence": {
                "sim_state": {
                    "status": "restored",
                    "digest": digest_of({"condition": condition, "fixture": "initial-state"}),
                },
                "controller_state": {"status": "cleared"},
                "policy_state": {
                    "status": "not_applicable",
                    "reason": "feedforward policy without recurrent state",
                },
                "action_queue": {"status": "cleared", "length_after": 0},
                "rng": {"status": "seeded", "seed": 100 + cond_index},
            },
        },
        "identity": dict(identity) if identity else None,
        "task_outcome": {"claimed": claimed_outcome} if claimed_outcome else {"claimed": "unknown"},
        "validity": {"claimed": claimed_validity} if claimed_validity else {"claimed": "unknown"},
        "costs": {
            "wall": {"value": round(4.0 + 0.1 * cond_index, 3), "unit": "s"},
            "simulator_steps": {"value": STEPS, "unit": "steps"},
            "agent_tokens": {
                "value": None,
                "unit": "tokens",
                "missing": "not measured for a synthetic fixture",
            },
            "human_review": {
                "value": None,
                "unit": "s",
                "missing": "not measured for a synthetic fixture",
            },
        },
    }
    return run


@dataclass
class BundleData:
    case: dict
    runs: dict[str, dict]
    traces: dict[str, dict]
    confirmation: dict | None = None
    prior: list[dict] = field(default_factory=list)
    chunk_length: int = 1

    def add_run(self, run: dict, behaviour: str, obs_source: str = "sensor") -> None:
        self.runs[run["id"]] = run
        self.traces[run["id"]] = make_trace(
            run["id"],
            COND_INDEX[run["condition_id"]],
            behaviour,
            chunk_length=self.chunk_length,
            obs_source=obs_source,
        )

    def set_behaviour(self, run_id: str, behaviour: str, obs_source: str = "sensor") -> None:
        run = self.runs[run_id]
        self.traces[run_id] = make_trace(
            run_id,
            COND_INDEX[run["condition_id"]],
            behaviour,
            chunk_length=self.chunk_length,
            obs_source=obs_source,
        )

    def set_candidate(self, candidate: dict, obs_source: str = "sensor") -> None:
        for run_id, run in self.runs.items():
            if run.get("candidate") is not None:
                run["candidate"] = candidate
                if obs_source != "sensor":
                    self.set_behaviour(run_id, "healthy", obs_source)
        if self.confirmation:
            self.confirmation["candidate"] = {
                "id": candidate["id"],
                "digest": candidate["digest"],
                "frozen_at": wall(FREEZE),
            }

    def candidate_run_ids(self) -> list[str]:
        return [rid for rid, run in self.runs.items() if run.get("candidate") is not None]


def positive_bundle(
    *, chunk_length: int = 1, max_age_ms: float = 60, strict: bool = False
) -> BundleData:
    """The valid positive control: reference, regression, exploration, frozen candidate, fresh pairs.

    ``strict`` declares obligation v0.2: per-run identity, a post-freeze reproduction run,
    declared deployability and acquisition stamps are then required rather than reported.
    """
    data = BundleData(case=make_case(max_age_ms), runs={}, traces={}, chunk_length=chunk_length)
    if strict:
        data.case["obligation"] = OBLIGATION_V02
    data.add_run(make_run("run-ref-000", "working", REPRODUCTION, T0), "healthy")
    data.add_run(
        make_run("run-reg-000", "changed", REPRODUCTION, T0 + timedelta(minutes=5)), "stale"
    )
    data.add_run(
        make_run(
            "run-explore-000",
            "changed",
            REPRODUCTION,
            T0 + timedelta(minutes=10),
            candidate=GUARD,
            plan=GUARD_PLAN,
        ),
        "healthy",
    )
    data.add_run(
        make_run(
            "run-conf-000",
            "changed",
            REPRODUCTION,
            FREEZE + timedelta(minutes=1),
            candidate=GUARD,
            plan=GUARD_PLAN,
        ),
        "healthy",
    )
    assignments = [
        {
            "condition_id": REPRODUCTION,
            "reference_run_id": "run-ref-000",
            "candidate_run_id": "run-conf-000",
        }
    ]
    for offset, condition in enumerate(FRESH, start=1):
        data.add_run(
            make_run(
                f"run-ref-{condition[-3:]}",
                "working",
                condition,
                FREEZE + timedelta(minutes=1 + offset),
            ),
            "healthy",
        )
        data.add_run(
            make_run(
                f"run-conf-{condition[-3:]}",
                "changed",
                condition,
                FREEZE + timedelta(minutes=4 + offset),
                candidate=GUARD,
                plan=GUARD_PLAN,
            ),
            "healthy",
        )
        assignments.append(
            {
                "condition_id": condition,
                "reference_run_id": f"run-ref-{condition[-3:]}",
                "candidate_run_id": f"run-conf-{condition[-3:]}",
            }
        )
    data.confirmation = {
        "schema": "nisayon.confirmation.v1",
        "id": "confirmation-001",
        "case_id": CASE_ID,
        "evidence_origin": ORIGIN,
        "protocol": {"id": PROTOCOL_ID, "predicates_digest": digest_of(data.case["predicates"])},
        "candidate": {"id": GUARD["id"], "digest": GUARD["digest"], "frozen_at": wall(FREEZE)},
        "conditions": [
            {"id": REPRODUCTION, "role": "reproduction", "generated_by": "the registered failure"}
        ]
        + [
            {"id": c, "role": "fresh", "generated_by": f"fixture seed {100 + COND_INDEX[c]}"}
            for c in FRESH
        ],
        "exploration_condition_ids": [REPRODUCTION],
        "exploration_run_ids": ["run-explore-000"],
        "assignments": assignments,
        "contamination": {"declared": "none"},
    }
    if strict:
        for run in data.runs.values():
            run["identity"] = dict(IDENTITY)
        data.confirmation["identity"] = dict(IDENTITY)
    return data


def pretty(obj: object) -> str:
    return json.dumps(obj, indent=2, sort_keys=True, ensure_ascii=False, allow_nan=False) + "\n"


def trace_bytes(trace: dict) -> bytes:
    return (canonical_json(trace) + "\n").encode()


def write_bundle(data: BundleData, path: Path) -> Path:
    path = Path(path)
    (path / "runs").mkdir(parents=True, exist_ok=True)
    (path / "artifacts").mkdir(exist_ok=True)
    (path / "case.json").write_text(pretty(data.case))
    for run_id, run in data.runs.items():
        raw = trace_bytes(data.traces[run_id])
        relative = f"artifacts/{run_id}.trace.json"
        (path / relative).write_bytes(raw)
        record = {**run, "trace_ref": {"path": relative, "sha256": sha256_bytes(raw)}}
        (path / "runs" / f"{run_id}.json").write_text(pretty(record))
    if data.confirmation is not None:
        (path / "confirmation.json").write_text(pretty(data.confirmation))
    if data.prior:
        (path / "prior").mkdir(exist_ok=True)
        for record in data.prior:
            (path / "prior" / f"{record['id']}.json").write_text(pretty(record))
    (path / "FIXTURE.md").write_text(README)
    return path


def rewrite_trace(bundle: Path, run_id: str, transform: Callable[[str], str]) -> None:
    """Rewrite a trace file and keep the run record's digest consistent with the new bytes."""
    trace_path = bundle / "artifacts" / f"{run_id}.trace.json"
    raw = transform(trace_path.read_text()).encode()
    trace_path.write_bytes(raw)
    run_path = bundle / "runs" / f"{run_id}.json"
    record = json.loads(run_path.read_text())
    record["trace_ref"]["sha256"] = sha256_bytes(raw)
    run_path.write_text(pretty(record))


