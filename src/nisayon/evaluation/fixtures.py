def wall(stamp: datetime) -> dict:
    return {"value": stamp.isoformat(), "clock": "wall_utc"}


def sim(seconds: float) -> dict:
    return {"value": round(seconds, 6), "unit": "s", "clock": "sim"}


def height_profile(profile: str, cond_index: int) -> list[float]:
    start = 8 + cond_index % 3
    heights = []
    for i in range(STEPS):
        lifted = max(0, i - start + 1)
        match profile:
            case "healthy":
                value = min(0.06, 0.005 * lifted)
            case "weak":
                value = min(0.03, 0.005 * lifted)
            case "stale":
                value = (
                    min(0.015, 0.005 * lifted)
                    if lifted <= 3
                    else max(0.0, 0.015 - 0.003 * (lifted - 3))
                )
            case _:
                value = 0.0
        heights.append(round(value, 6))
    return heights


def make_trace(
    run_id: str,
    cond_index: int,
    behaviour: str,
    *,
    chunk_length: int = 1,
    obs_source: str = "sensor",
) -> dict:
    spec = BEHAVIOURS[behaviour]
    heights = height_profile(spec["profile"], cond_index)
    start = 8 + cond_index % 3
    steps = []
    for i in range(STEPS):
        t = i * DT
        chunk = None
        chunk_start = i
        if chunk_length > 1:
            chunk_start = (i // chunk_length) * chunk_length
            chunk = {
                "id": f"chunk-{chunk_start:03d}",
                "index": i - chunk_start,
                "length": chunk_length,
            }
        source_index = max(0, chunk_start - spec["lag"])
        lifting = i >= start and heights[i] < 0.06
        action = (
            [0.0, 0.0, 0.0]
            if spec["zero_actions"]
            else [round(0.001 * cond_index, 6), 0.0, 0.01 if lifting else 0.0]
        )
        action_record = {
            "computed_from": f"obs-{source_index:03d}",
            "t_executed": sim(t + 0.005),
            "intended": action,
            "executed": action,
            "host": {
                "inference_started_s": round(t + 0.002, 6),
                "inference_finished_s": round(t + 0.004, 6),
                "executed_s": round(t + 0.005, 6),
            },
        }
        if chunk is not None:
            action_record["chunk"] = chunk
        steps.append(
            {
                "step": i,
                "observation": {
                    "id": f"obs-{i:03d}",
                    "t": sim(t),
                    "source": obs_source,
                    "provenance": {"kind": "closed_loop"},
                    "capture": {
                        "received_host_s": round(t + 0.001, 6),
                        "components": {
                            "sensor": {
                                "sequence": i + 1,
                                "simulation_s": round(t, 6),
                                "host_started_s": round(t, 6),
                                "host_finished_s": round(t + 0.0005, 6),
                            }
                        },
                    },
                },
                "action": action_record,
                "measurements": {
                    "cube_height_m": heights[i],
                    "max_joint_speed_rad_s": 0.0 if spec["zero_actions"] else 0.4,
                    "table_contact": 0,
                },
            }
        )
    return {
        "schema": "nisayon.trace.v1",
        "run_id": run_id,
        "evidence_origin": ORIGIN,
        "measurement_units": dict(UNITS),
        "steps": steps,
    }


