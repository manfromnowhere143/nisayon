def _corrupt_after_write(bundle: Path) -> None:
    path = bundle / "artifacts" / "run-conf-000.trace.json"
    path.write_bytes(path.read_bytes() + b" ")


def _remove_after_write(bundle: Path) -> None:
    (bundle / "artifacts" / "run-conf-000.trace.json").unlink()


def _relabelled_as_simulator() -> BundleData:
    data = positive_bundle()
    data.case["evidence_origin"] = "simulator"
    for run in data.runs.values():
        run["evidence_origin"] = "simulator"
    data.confirmation["evidence_origin"] = "simulator"
    return data


def _timeout() -> BundleData:
    data = positive_bundle()
