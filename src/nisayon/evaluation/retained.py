"""An index of the retained decisions and scores in a results directory.

A row repeats what the retained file says; it is a table of contents, not new evidence.
"""

from __future__ import annotations

import json
from pathlib import Path

INDEX_SCHEMA = "nisayon.evaluation.index.v1"


def _premise(value: object) -> str:
    if value is True:
        return "yes"
    if value is False:
        return "no"
    if value is None:
        return "n/a"
    return "?"


def _codes(items: object) -> list[str]:
    return sorted(
        {
            str(item.get("code"))
            for item in (items or [])
            if isinstance(item, dict) and item.get("code")
        }
    )


def collect_index(directory: Path) -> dict:
    directory = Path(directory)
    decisions: list[dict] = []
    for path in sorted(directory.glob("*.decision.json")):
        try:
            data = json.loads(path.read_text())
        except (OSError, ValueError) as error:
            decisions.append({"name": path.name, "error": str(error)})
            continue
        if not isinstance(data, dict):
            decisions.append({"name": path.name, "error": "not a JSON object"})
            continue
        premises = data.get("premises") if isinstance(data.get("premises"), dict) else {}
        obligation = data.get("obligation")
        evidence = data.get("evidence") if isinstance(data.get("evidence"), dict) else {}
        decisions.append(
            {
                "name": path.name.removesuffix(".decision.json"),
                "case_id": data.get("case_id"),
                "decision": data.get("decision"),
                "obligation": obligation.get("version")
                if isinstance(obligation, dict)
                else obligation,
                "reference_established": premises.get("reference_established"),
                "regression_reproduced": premises.get("regression_reproduced"),
                "reasons": _codes(data.get("reasons")),
                "artifacts": evidence.get("artifacts"),
                "runs": len(data.get("runs") or {}),
                "evaluation_wall_s": data.get("evaluation_wall_s"),
            }
        )
    scores: list[dict] = []
    for path in sorted(directory.glob("*.score.json")):
        try:
            data = json.loads(path.read_text())
        except (OSError, ValueError) as error:
            scores.append({"name": path.name, "error": str(error)})
            continue
        if not isinstance(data, dict):
            scores.append({"name": path.name, "error": "not a JSON object"})
            continue
        arms = data.get("arms") if isinstance(data.get("arms"), dict) else {}
        scores.append(
            {
                "name": path.name.removesuffix(".score.json"),
                "fair": data.get("fair"),
                "findings": _codes(data.get("findings")),
                "arms": {
                    str(arm): {
                        "confirmed": (item.get("outcomes") or {}).get("confirmed"),
                        "false_acceptances": item.get("false_acceptances"),
                    }
                    for arm, item in arms.items()
                    if isinstance(item, dict)
                },
            }
        )
    packages: list[dict] = []
    for path in sorted(directory.glob("*.package-check.json")):
        try:
            data = json.loads(path.read_text())
        except (OSError, ValueError) as error:
            packages.append({"name": path.name, "error": str(error)})
            continue
        if not isinstance(data, dict):
            packages.append({"name": path.name, "error": "not a JSON object"})
            continue
        packages.append(
            {
                "name": path.name.removesuffix(".package-check.json"),
                "ready": data.get("ready_for_reserved_screen"),
                "findings": _codes(data.get("findings")),
                "frozen_at": data.get("package_frozen_at"),
            }
        )
    return {
        "schema": INDEX_SCHEMA,
        "directory": str(directory),
        "decisions": decisions,
        "scores": scores,
        "packages": packages,
    }


def render_index(index: dict) -> str:
    name = Path(index["directory"]).name
    lines = [
        f"# Retained decisions in `{name}`",
        "",
        "Generated by `python -m nisayon.evaluation index`. A row repeats what the retained",
        "file says; the `.txt` beside each `.decision.json` is the readable rendering.",
        "",
        "| record | decision | obligation | reference | regression | reasons | artifacts | runs | wall s |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for item in index["decisions"]:
        if "error" in item:
            lines.append(f"| {item['name']} | unreadable | | | | {item['error']} | | | |")
            continue
        wall = item["evaluation_wall_s"]
        lines.append(
            f"| {item['name']} | {item['decision']} | {item['obligation'] or ''} | "
            f"{_premise(item['reference_established'])} | "
            f"{_premise(item['regression_reproduced'])} | "
            f"{', '.join(item['reasons']) or 'none'} | {item['artifacts'] or ''} | "
            f"{item['runs']} | {'' if wall is None else wall} |"
        )
    if index["scores"]:
        lines += ["", "| score | fair | findings | arms |", "|---|---|---|---|"]
        for item in index["scores"]:
            if "error" in item:
                lines.append(f"| {item['name']} | unreadable | {item['error']} | |")
                continue
            arms = "; ".join(
                f"{arm}: confirmed {values['confirmed']}, false acceptances "
                f"{values['false_acceptances']}"
                for arm, values in item["arms"].items()
            )
            fair = "yes" if item["fair"] is True else "no" if item["fair"] is False else "?"
            lines.append(
                f"| {item['name']} | {fair} | {', '.join(item['findings']) or 'none'} | {arms} |"
            )
    if index.get("packages"):
        lines += ["", "| screen package | ready | findings | frozen |", "|---|---|---|---|"]
        for item in index["packages"]:
            if "error" in item:
                lines.append(f"| {item['name']} | unreadable | {item['error']} | |")
                continue
            ready = "yes" if item["ready"] is True else "no" if item["ready"] is False else "?"
            lines.append(
                f"| {item['name']} | {ready} | {', '.join(item['findings']) or 'none'} | "
                f"{item['frozen_at'] or ''} |"
            )
    return "\n".join(lines) + "\n"
