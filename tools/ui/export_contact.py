"""Generate a verified, data-only public example from one native contact run."""

import argparse
import hashlib
import json
import zipfile
from pathlib import Path

from nisayon.engine.io import canonical_bytes
from nisayon.lab import execute, experiment, inspect_packet


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, required=True, help="create-only native packet")
    parser.add_argument("--app", type=Path, default=Path("apps/instrument"))
    args = parser.parse_args()
    result = execute(experiment(), args.out)
    if result["status"] != "complete":
        raise ValueError("Preview requires a complete execution, including its negative decision")
    packet = inspect_packet(args.out, expected_sha256=result["packet_sha256"])
    raw = canonical_bytes(packet)
    sha = hashlib.sha256(raw).hexdigest()
    public = args.app / "public" / "media" / "contact"
    public.mkdir(parents=True, exist_ok=True)
    name = f"contact-{sha[:16]}"
    (public / (name + ".json")).write_bytes(raw)
    with zipfile.ZipFile(
        public / (name + ".zip"), "w", compression=zipfile.ZIP_DEFLATED
    ) as archive:
        for path in sorted(args.out.iterdir()):
            archive.writestr(path.name, path.read_bytes())
    pin = {
        "path": "/media/contact/" + name + ".json",
        "archive": "/media/contact/" + name + ".zip",
        "sha256": sha,
    }
    (args.app / "src" / "lab" / "contactPreview.ts").write_text(
        "// Generated by tools/ui/export_contact.py from a verified native packet.\nexport const CONTACT_PREVIEW = "
        + json.dumps(pin, indent=2)
        + " as const;\n"
    )
    print(
        json.dumps(
            {
                **pin,
                "experiment_id": packet["experiment"]["experiment_id"],
                "packet_sha256": packet["packet_sha256"],
            },
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
